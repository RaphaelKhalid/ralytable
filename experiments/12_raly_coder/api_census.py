"""Census the fixed Python API surface behind the Raly Coder actions."""

from __future__ import annotations

import ast
import builtins
import importlib
import inspect
import json
from pathlib import Path
import sys
from typing import Any


STACK = {
    "runtime": "Python 3.12 standard library",
    "source_model": "Python modules parsed with ast",
    "test_runner": ["python", "-m", "unittest", "discover", "-s", "tests", "-p", "test_*.py"],
    "network": "disabled by evaluator",
    "shell": "not exposed to model",
}

ACTION_APIS: dict[str, list[str]] = {
    "find_symbol": [
        "ast.parse", "ast.walk", "ast.FunctionDef", "ast.AsyncFunctionDef",
        "ast.ClassDef", "ast.get_source_segment",
    ],
    "open_file": [
        "pathlib.Path.resolve", "pathlib.Path.is_file", "pathlib.Path.read_bytes",
        "str.splitlines", "hashlib.sha256",
    ],
    "read_region": [
        "pathlib.Path.resolve", "pathlib.Path.is_file", "pathlib.Path.read_bytes",
        "str.splitlines", "hashlib.sha256",
    ],
    "apply_patch": [
        "pathlib.Path.resolve", "pathlib.Path.is_file", "pathlib.Path.read_bytes",
        "str.count", "str.replace", "pathlib.Path.write_text", "hashlib.sha256",
    ],
    "run_tests": [
        "sys.executable", "subprocess.run", "subprocess.TimeoutExpired",
        "subprocess.CompletedProcess", "unittest.discover",
    ],
    "inspect_failure": [
        "re.search", "str.splitlines", "json.dumps",
    ],
}


def resolve(qualified: str) -> Any:
    module_name, attr_path = qualified.split(".", 1)
    if hasattr(builtins, module_name):
        module = getattr(builtins, module_name)
    else:
        module = importlib.import_module(module_name)
    value: Any = module
    for part in attr_path.split("."):
        value = getattr(value, part)
    return value


def signature(qualified: str) -> str:
    try:
        value = resolve(qualified)
        if inspect.isclass(value) and qualified in {"ast.FunctionDef", "ast.AsyncFunctionDef", "ast.ClassDef"}:
            return "AST node class"
        return str(inspect.signature(value))
    except (TypeError, ValueError, AttributeError):
        return "unavailable"


def build_census() -> dict[str, Any]:
    all_apis = sorted({api for apis in ACTION_APIS.values() for api in apis})
    rows = []
    for api in all_apis:
        rows.append({"api": api, "signature": signature(api)})
    return {
        "schema": "raly-coder-api-census-v1",
        "python": sys.version,
        "stack": STACK,
        "actions": {
            name: {"api_count_in_action": len(apis), "apis": apis}
            for name, apis in ACTION_APIS.items()
        },
        "unique_api_count": len(all_apis),
        "unique_apis": rows,
    }


def markdown(census: dict[str, Any]) -> str:
    lines = [
        "# Raly Coder Python API vocabulary census",
        "",
        "Generated by `api_census.py`; this records the model-facing action",
        "vocabulary's fixed standard-library implementation surface.",
        "",
        f"- Schema: `{census['schema']}`",
        f"- Runtime: `{census['python'].split()[0]}`",
        f"- Unique referenced APIs: **{census['unique_api_count']}**",
        "- The model cannot provide shell commands, paths outside the sandbox,",
        "  network access, or a custom test command.",
        "",
        "| action | referenced calls |",
        "|---|---|",
    ]
    for action, data in census["actions"].items():
        lines.append(f"| `{action}` | " + ", ".join(f"`{api}`" for api in data["apis"]) + " |")
    lines += ["", "## Signatures", "", "| API | signature |", "|---|---|"]
    for row in census["unique_apis"]:
        lines.append(f"| `{row['api']}` | `{row['signature']}` |")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    root = Path(__file__).resolve().parent
    census = build_census()
    (root / "api_census.json").write_text(json.dumps(census, indent=2) + "\n", encoding="utf-8")
    (root / "API_CENSUS.md").write_text(markdown(census), encoding="utf-8")
    print(json.dumps({"unique_api_count": census["unique_api_count"], "actions": list(census["actions"])}, indent=2))


if __name__ == "__main__":
    main()
